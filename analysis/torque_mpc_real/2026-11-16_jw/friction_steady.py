"""바퀴 띄움, 38~39 °C, 정상 상태 (명령 0.045/0.04/0.035/0.03 N·m 각 3 s 의 마지막 1 s): τ_명령 = τc + bv·ω 맞춤 → 설정 보상표와 비교."""
import numpy as np
SS = {"FL": [(0.045, 25.68), (0.04, 21.19), (0.035, 16.94), (0.03, 11.51)],
      "FR": [(0.045, 20.88), (0.04, 16.96), (0.035, 12.76), (0.03, 7.92)],
      "RL": [(0.045, 26.20), (0.04, 22.33), (0.035, 17.80), (0.03, 12.77)],
      "RR": [(0.045, 24.61), (0.04, 20.82), (0.035, 16.76), (0.03, 11.86)]}
CFG = {"FL": (0.02142, 0.002062), "FR": (0.02151, 0.001799), "RL": (0.02170, 0.001767), "RR": (0.01830, 0.001679)}
print("바퀴 | 지금 τc     bv        잔차최대 | 설정 τc   bv       | @10 / 20 rad/s 지금 vs 0.9×설정 보상 [N·m] | 보상 − 지금 @20")
for n, pts in SS.items():
    tau, w = np.array(pts).T
    b, c = np.polyfit(w, tau, 1); r = np.max(np.abs(np.polyval([b, c], w) - tau))
    now = lambda x: c + b * x; comp = lambda x: 0.9 * (CFG[n][0] + CFG[n][1] * x)
    print(f" {n}  | {c:.4f}  {b:.6f}  {1e3*r:.1f} mN·m | {CFG[n][0]:.4f} {CFG[n][1]:.6f} | {now(10):.4f}/{now(20):.4f} vs {comp(10):.4f}/{comp(20):.4f}       | {comp(20)-now(20):+.4f}")
